import { defineComponent, h, nextTick } from 'vue';

import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { flushPromises, mount } from '@vue/test-utils';
import { createTestingPinia } from '@pinia/testing';

import AegisActions from '@/components/Aegis/AegisActions.vue';

import { useFlaw } from '@/composables/useFlaw';

import { mountWithConfig } from '@/__tests__/helpers';
import { useToastStore } from '@/stores/ToastStore';

const warningSelector = '[role="button"][aria-label="AI-Bot suggestion unavailable"]';
const detailsSelector = '[role="button"][aria-label="AI suggestion details"]';
const copySelector = 'button[aria-label="Copy text"]';
const closeSelector = 'button[aria-label="Close suggestion details"]';
const literalText = '<img src=x onerror="alert(1)"> & <script>alert(2)</script> "quoted" \'text\' &lt;b&gt;<br>';
const skipText = [
  'Suggestion unavailable',
  `Reason: ${literalText}`,
  '',
  'Discarded suggestion: CWE-89',
  'Confidence: 0.42',
  'Data quality: 0.75',
  'Tools used: <external_references_tool>',
].join('\n');
const detailsText = [
  'Generated by Aegis-AI',
  `Explanation: ${literalText}`,
  '',
  'Confidence: 0.88',
  'Data quality: 0.90',
  'Tools used: analyzer & parser',
].join('\n');
const defaultProps = {
  canShowFeedback: false,
  canSuggest: false,
  hasAppliedSuggestion: true,
  hasMultipleSuggestions: false,
  isFetchingSuggestion: false,
  selectedIndex: 0,
  suggestions: ['CWE-79'],
  tooltipText: detailsText,
};
const popupVariants = [
  {
    name: 'skip warning',
    triggerSelector: warningSelector,
    text: skipText,
    textProp: 'skipTooltipText' as const,
    props: {
      ...defaultProps,
      hasAppliedSuggestion: false,
      skipTooltipText: skipText,
    },
  },
  {
    name: 'regular suggestion details',
    triggerSelector: detailsSelector,
    text: detailsText,
    textProp: 'tooltipText' as const,
    props: {
      ...defaultProps,
      skipTooltipText: 'Historical skip that must not be shown or copied',
    },
  },
];
const writeText = vi.fn<(text: string) => Promise<void>>();
const wrappers: { unmount(): void }[] = [];
const interactionEventTypes = ['pointerdown', 'mousedown', 'pointerup', 'mouseup', 'click'] as const;
let host: HTMLDivElement;
let originalClipboard: PropertyDescriptor | undefined;

function mountActions(props: InstanceType<typeof AegisActions>['$props']) {
  const wrapper = mountWithConfig(AegisActions, { props, attachTo: host });
  wrappers.push(wrapper);
  return wrapper;
}

function mountWithRealTeleport(props: InstanceType<typeof AegisActions>['$props']) {
  const elevatedCvssLayer = document.createElement('div');
  elevatedCvssLayer.className = 'input-wrapper';
  elevatedCvssLayer.style.zIndex = '3';
  host.append(elevatedCvssLayer);
  const wrapper = mount(AegisActions, {
    attachTo: host,
    props,
    global: {
      directives: { osimLoading: { mounted: vi.fn() } },
      plugins: [createTestingPinia()],
      stubs: { Teleport: false },
    },
  });
  wrappers.push(wrapper);
  return { elevatedCvssLayer, wrapper };
}

async function openPopup(variant: typeof popupVariants[number]) {
  const wrapper = mountActions(variant.props);
  const trigger = wrapper.get<HTMLElement>(variant.triggerSelector);
  trigger.element.focus();
  await trigger.trigger('keydown', { key: 'Enter' });
  return { trigger, wrapper };
}

function mountEventHarness(props: InstanceType<typeof AegisActions>['$props']) {
  const ancestorEvent = vi.fn<(event: Event) => void>();
  const Harness = defineComponent({
    render() {
      return h('div', {
        class: 'event-harness',
        onClick: ancestorEvent,
        onMousedown: ancestorEvent,
        onMouseup: ancestorEvent,
        onPointerdown: ancestorEvent,
        onPointerup: ancestorEvent,
      }, [h(AegisActions, props)]);
    },
  });
  const wrapper = mountWithConfig(Harness, { attachTo: host });
  wrappers.push(wrapper);
  return { actions: wrapper.getComponent(AegisActions), ancestorEvent };
}

function dispatchInteraction(target: Element) {
  return interactionEventTypes.map((type) => {
    const event = new MouseEvent(type, { bubbles: true, cancelable: true });
    target.dispatchEvent(event);
    return event;
  });
}

function copyButtonText(wrapper: ReturnType<typeof mountWithConfig>) {
  return wrapper.get(copySelector).text();
}

beforeEach(() => {
  useFlaw().resetFlaw();
  host = document.createElement('div');
  document.body.append(host);
  originalClipboard = Object.getOwnPropertyDescriptor(navigator, 'clipboard');
  writeText.mockReset().mockResolvedValue(undefined);
  Object.defineProperty(navigator, 'clipboard', {
    configurable: true,
    value: { writeText },
  });
});

afterEach(() => {
  for (const wrapper of wrappers.splice(0)) wrapper.unmount();
  document.getSelection()?.removeAllRanges();
  host.remove();
  if (originalClipboard) Object.defineProperty(navigator, 'clipboard', originalClipboard);
  else Reflect.deleteProperty(navigator, 'clipboard');
});

describe.each(popupVariants)('$name popup', (variant) => {
  const { props, text, textProp, triggerSelector } = variant;

  it.each(['click', 'Enter', ' '])('opens and toggles closed using %j', async (activation) => {
    const wrapper = mountActions(props);
    const trigger = wrapper.get<HTMLElement>(triggerSelector);
    const activate = () => activation === 'click'
      ? trigger.trigger('click')
      : trigger.trigger('keydown', { key: activation });

    trigger.element.focus();
    expect(document.activeElement).toBe(trigger.element);
    expect(trigger.attributes('aria-expanded')).toBe('false');
    expect(trigger.attributes('aria-haspopup')).toBe('dialog');
    expect(trigger.attributes('aria-describedby')).toBeUndefined();

    await activate();

    const dialog = wrapper.get('[role="dialog"]');
    expect(dialog.isVisible()).toBe(true);
    expect(dialog.attributes('aria-label')).toBe(trigger.attributes('aria-label'));
    expect(trigger.attributes('aria-expanded')).toBe('true');
    expect(trigger.attributes('aria-describedby')).toBe(dialog.attributes('id'));
    expect(document.activeElement).toBe(dialog.get<HTMLButtonElement>(copySelector).element);

    await activate();

    expect(wrapper.find('[role="dialog"]').exists()).toBe(false);
    expect(trigger.attributes('aria-expanded')).toBe('false');
    expect(trigger.attributes('aria-describedby')).toBeUndefined();
  });

  it('contains popup interactions while preserving text selection and button activation', async () => {
    const { actions: wrapper, ancestorEvent } = mountEventHarness(props);
    const trigger = wrapper.get<HTMLElement>(triggerSelector);
    trigger.element.focus();
    await trigger.trigger('keydown', { key: 'Enter' });
    expect(document.activeElement).toBe(wrapper.get<HTMLButtonElement>(copySelector).element);

    const content = wrapper.get<HTMLElement>('.aegis-tooltip-content');
    const contentEvents = dispatchInteraction(content.element);
    // JSDOM does not perform the browser's default blur when clicking non-focusable text.
    wrapper.get<HTMLButtonElement>(copySelector).element.blur();
    await nextTick();

    expect(document.activeElement).toBe(document.body);
    expect(wrapper.find('.aegis-tooltip').exists()).toBe(true);
    expect(contentEvents.every(event => !event.defaultPrevented)).toBe(true);
    expect(ancestorEvent).not.toHaveBeenCalled();
    expect(writeText).not.toHaveBeenCalled();

    const range = document.createRange();
    range.selectNodeContents(content.element);
    const selection = document.getSelection()!;
    selection.addRange(range);

    expect(selection.toString()).toContain(literalText);
    expect(wrapper.get('[role="dialog"]').isVisible()).toBe(true);

    const close = wrapper.get<HTMLButtonElement>(closeSelector);
    const closeEvents = dispatchInteraction(close.element);
    await nextTick();

    expect(closeEvents.every(event => !event.defaultPrevented)).toBe(true);
    expect(ancestorEvent).not.toHaveBeenCalled();
    expect(writeText).not.toHaveBeenCalled();
    expect(wrapper.find('[role="dialog"]').exists()).toBe(false);

    await trigger.trigger('keydown', { key: 'Enter' });
    const copy = wrapper.get<HTMLButtonElement>(copySelector);
    const copyLabel = copy.get('span');
    const copyEvents = dispatchInteraction(copyLabel.element);
    await flushPromises();

    expect(copyEvents.every(event => !event.defaultPrevented)).toBe(true);
    expect(ancestorEvent).not.toHaveBeenCalled();
    expect(writeText).toHaveBeenCalledExactlyOnceWith(text);
    expect(copyButtonText(wrapper)).toBe('Copied text');
    expect(wrapper.get('[role="dialog"]').isVisible()).toBe(true);
  });

  it('copies literal plain text without closing and confirms only after the write succeeds', async () => {
    let finishWrite!: () => void;
    writeText.mockReturnValueOnce(new Promise<void>((resolve) => { finishWrite = resolve; }));
    const { wrapper } = await openPopup(variant);
    const copy = wrapper.get<HTMLButtonElement>(copySelector);

    copy.element.focus();
    await nextTick();
    expect(document.activeElement).toBe(copy.element);
    expect(wrapper.get('[role="dialog"]').isVisible()).toBe(true);
    expect(wrapper.get('.aegis-tooltip-content').text()).toContain(literalText);
    expect(wrapper.find('.aegis-tooltip-content img, .aegis-tooltip-content script').exists()).toBe(false);

    await copy.trigger('click');

    expect(writeText).toHaveBeenCalledExactlyOnceWith(text);
    expect(copyButtonText(wrapper)).toBe('Copy text');
    expect(wrapper.get('[role="dialog"]').isVisible()).toBe(true);

    finishWrite();
    await flushPromises();

    expect(copyButtonText(wrapper)).toBe('Copied text');
    expect(wrapper.get('[role="dialog"]').isVisible()).toBe(true);
    expect(useToastStore().addToast).not.toHaveBeenCalled();
  });

  it('copies refreshed long details in full and resets copy confirmation on change and reopen', async () => {
    const { trigger, wrapper } = await openPopup(variant);
    const copy = wrapper.get<HTMLButtonElement>(copySelector);
    await copy.trigger('click');
    await flushPromises();
    expect(copyButtonText(wrapper)).toBe('Copied text');

    const updatedText = [
      'Updated suggestion details',
      literalText,
      '',
      ...Array.from({ length: 100 }, (_, index) => `Detail ${index}: keep every line & literal <value>`),
      'Last detail: do not truncate this line',
      '',
    ].join('\n');
    await wrapper.setProps({ [textProp]: updatedText });

    expect(copyButtonText(wrapper)).toBe('Copy text');
    expect(wrapper.get('[role="dialog"]').text()).toContain('Last detail: do not truncate this line');
    await copy.trigger('click');
    await flushPromises();

    expect(writeText.mock.calls).toEqual([[text], [updatedText]]);
    expect(copyButtonText(wrapper)).toBe('Copied text');
    expect(wrapper.get('[role="dialog"]').isVisible()).toBe(true);

    await wrapper.get(closeSelector).trigger('click');
    await trigger.trigger('keydown', { key: 'Enter' });
    expect(wrapper.get(copySelector).text()).toBe('Copy text');
  });

  it('does not confirm newly displayed details when an older clipboard write finishes', async () => {
    let finishWrite!: () => void;
    writeText.mockReturnValueOnce(new Promise<void>((resolve) => { finishWrite = resolve; }));
    const { wrapper } = await openPopup(variant);
    const copy = wrapper.get(copySelector);
    await copy.trigger('click');

    const updatedText = `New current details\n${literalText}`;
    await wrapper.setProps({ [textProp]: updatedText });
    finishWrite();
    await flushPromises();

    expect(writeText).toHaveBeenCalledExactlyOnceWith(text);
    expect(copyButtonText(wrapper)).toBe('Copy text');
    expect(wrapper.get('[role="dialog"]').text()).toContain('New current details');

    await copy.trigger('click');
    await flushPromises();
    expect(writeText.mock.calls).toEqual([[text], [updatedText]]);
    expect(copyButtonText(wrapper)).toBe('Copied text');
  });

  it.each(['denied', 'unavailable'])('handles %s clipboard access without false success', async (failure) => {
    if (failure === 'denied') {
      writeText.mockRejectedValueOnce(new DOMException('Clipboard permission denied', 'NotAllowedError'));
    } else {
      Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined });
    }
    const { wrapper } = await openPopup(variant);
    const copy = wrapper.get<HTMLButtonElement>(copySelector);
    copy.element.focus();
    await copy.trigger('click');
    await flushPromises();

    expect(copyButtonText(wrapper)).toBe('Copy text');
    expect(wrapper.get('[role="dialog"]').isVisible()).toBe(true);
    expect(useToastStore().addToast).toHaveBeenCalledExactlyOnceWith(expect.objectContaining({
      title: 'Copy failed',
      body: expect.stringMatching(/select and copy the text manually/i),
      css: 'warning',
    }));
  });

  it('clears an earlier success if a later clipboard write fails', async () => {
    const { wrapper } = await openPopup(variant);
    const copy = wrapper.get(copySelector);
    await copy.trigger('click');
    await flushPromises();
    expect(copyButtonText(wrapper)).toBe('Copied text');

    writeText.mockRejectedValueOnce(new DOMException('Clipboard permission denied', 'NotAllowedError'));
    await copy.trigger('click');
    await flushPromises();

    expect(copyButtonText(wrapper)).toBe('Copy text');
    expect(wrapper.get('[role="dialog"]').isVisible()).toBe(true);
    expect(useToastStore().addToast).toHaveBeenCalledOnce();
  });

  it.each(['close button', 'Escape'])('closes with %s and returns focus to the trigger', async (dismissal) => {
    const { trigger, wrapper } = await openPopup(variant);
    const control = wrapper.get<HTMLButtonElement>(dismissal === 'close button' ? closeSelector : copySelector);
    control.element.focus();
    await nextTick();
    expect(document.activeElement).toBe(control.element);
    expect(wrapper.get('[role="dialog"]').isVisible()).toBe(true);

    if (dismissal === 'close button') await control.trigger('click');
    else await control.trigger('keydown', { key: 'Escape' });

    expect(wrapper.find('[role="dialog"]').exists()).toBe(false);
    expect(trigger.attributes('aria-expanded')).toBe('false');
    expect(document.activeElement).toBe(trigger.element);
    expect(writeText).not.toHaveBeenCalled();
  });

  it('dismisses when clicking outside the component', async () => {
    const { trigger, wrapper } = await openPopup(variant);
    const outside = document.createElement('button');
    outside.textContent = 'Another field';
    host.append(outside);
    outside.dispatchEvent(new MouseEvent('pointerdown', { bubbles: true }));
    outside.click();
    await nextTick();

    expect(wrapper.find('[role="dialog"]').exists()).toBe(false);
    expect(trigger.attributes('aria-expanded')).toBe('false');
    expect(trigger.attributes('aria-describedby')).toBeUndefined();
  });
});

it('stays closed when tooltip availability is removed and restored', async () => {
  const wrapper = mountActions(defaultProps);
  await wrapper.get(detailsSelector).trigger('click');
  expect(wrapper.get('[role="dialog"]').isVisible()).toBe(true);

  await wrapper.setProps({ hasAppliedSuggestion: false });
  expect(wrapper.find(detailsSelector).exists()).toBe(false);
  expect(wrapper.find('[role="dialog"]').exists()).toBe(false);

  await wrapper.setProps({ hasAppliedSuggestion: true });
  expect(wrapper.get(detailsSelector).attributes('aria-expanded')).toBe('false');
  expect(wrapper.find('[role="dialog"]').exists()).toBe(false);
});

it('copies only the chosen popup when different fields have details open', async () => {
  const warning = await openPopup(popupVariants[0]);
  const suggestion = await openPopup(popupVariants[1]);
  expect(warning.wrapper.get('[role="dialog"]').isVisible()).toBe(true);
  expect(suggestion.wrapper.get('[role="dialog"]').isVisible()).toBe(true);

  const copy = warning.wrapper.get<HTMLButtonElement>(copySelector);
  copy.element.focus();
  await copy.trigger('click');
  await flushPromises();

  expect(writeText).toHaveBeenCalledExactlyOnceWith(skipText);
  expect(copyButtonText(warning.wrapper)).toBe('Copied text');
  expect(warning.wrapper.get('[role="dialog"]').isVisible()).toBe(true);
  expect(suggestion.wrapper.find('[role="dialog"]').exists()).toBe(false);
});

describe.each(popupVariants)('$name popup with CVSS z-index isolation', (variant) => {
  it('teleports above the field subtree and retains all popup interactions', async () => {
    const { elevatedCvssLayer, wrapper } = mountWithRealTeleport(variant.props);
    const trigger = wrapper.get<HTMLElement>(variant.triggerSelector);
    trigger.element.focus();
    await trigger.trigger('click');
    await flushPromises();

    const dialogId = trigger.attributes('aria-describedby')!;
    const dialog = document.getElementById(dialogId)!;
    expect(dialog).toBeInstanceOf(HTMLElement);
    expect(dialog.parentElement).toBe(document.body);
    expect(host.contains(dialog)).toBe(false);
    expect(elevatedCvssLayer.parentElement).toBe(host);
    expect(dialog.style.position).toBe('fixed');
    expect(dialog.getAttribute('data-popper-placement')).toMatch(/^(right|left)$/);
    expect(document.activeElement).toBe(dialog.querySelector(copySelector));

    const content = dialog.querySelector<HTMLElement>('.aegis-tooltip-content')!;
    content.click();
    await nextTick();
    expect(document.getElementById(dialogId)).toBe(dialog);
    expect(writeText).not.toHaveBeenCalled();
    const range = document.createRange();
    range.selectNodeContents(content);
    const selection = document.getSelection()!;
    selection.addRange(range);
    expect(selection.toString()).toContain(literalText);

    const copy = dialog.querySelector<HTMLButtonElement>(copySelector)!;
    copy.click();
    await flushPromises();
    expect(writeText).toHaveBeenCalledExactlyOnceWith(variant.text);
    expect(document.getElementById(dialogId)).toBe(dialog);

    const close = dialog.querySelector<HTMLButtonElement>(closeSelector)!;
    close.click();
    await nextTick();
    expect(document.getElementById(dialogId)).toBeNull();
    expect(document.activeElement).toBe(trigger.element);

    await trigger.trigger('keydown', { key: 'Enter' });
    await flushPromises();
    const escapeDialog = document.getElementById(trigger.attributes('aria-describedby')!)!;
    escapeDialog.dispatchEvent(new KeyboardEvent('keydown', {
      bubbles: true,
      cancelable: true,
      key: 'Escape',
    }));
    await nextTick();
    expect(document.body.contains(escapeDialog)).toBe(false);
    expect(document.activeElement).toBe(trigger.element);

    await trigger.trigger('keydown', { key: 'Enter' });
    await flushPromises();
    const outsideDialog = document.getElementById(trigger.attributes('aria-describedby')!)!;
    elevatedCvssLayer.dispatchEvent(new MouseEvent('pointerdown', { bubbles: true }));
    elevatedCvssLayer.click();
    await nextTick();
    expect(document.body.contains(outsideDialog)).toBe(false);
    expect(trigger.attributes('aria-expanded')).toBe('false');
  });
});
