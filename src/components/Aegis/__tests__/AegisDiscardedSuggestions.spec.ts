import { nextTick, type Ref } from 'vue';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import AegisComponentActions from '@/components/Aegis/AegisComponentActions.vue';
import AegisCweActions from '@/components/Aegis/AegisCweActions.vue';

import { useAegisMetadataTracking } from '@/composables/aegis/useAegisMetadataTracking';
import { useFlaw } from '@/composables/useFlaw';

import { mountWithConfig } from '@/__tests__/helpers';
import { osimRuntime } from '@/stores/osimRuntime';
import type { AegisChangeEntry } from '@/types/aegisAI';
import type { OsimRuntimeType } from '@/types/zodOsim';

const tracking = useAegisMetadataTracking();
const runtime = osimRuntime as Ref<OsimRuntimeType>;
const wrappers: ReturnType<typeof mountWithConfig>[] = [];
const warningSelector = '[role="button"][aria-label="AI-Bot suggestion unavailable"]';
const untrustedValue = '<img src=x onerror="alert(1)"> & <b>\'quoted\'</b> &lt;script&gt;<br>';
const skip: AegisChangeEntry = {
  type: 'AI-Bot-Skipped',
  timestamp: '2026-10-20T10:00:00Z',
  skip_reason: 'confidence',
  skip_description: 'Confidence below the configured threshold',
  confidence: 0.4,
  data_quality: 0.8,
  tools_used: ['cve_tool'],
};
const fields = [
  {
    field: 'cwe_id',
    component: AegisCweActions,
    currentValue: 'CWE-89',
    rejectedValue: 'CWE-79',
    displayedValue: 'CWE-79',
    untrustedValue,
    displayedUntrustedValue: untrustedValue,
  },
  {
    field: 'components',
    component: AegisComponentActions,
    currentValue: ['kernel'],
    rejectedValue: ['openssl', 'libxml2'],
    displayedValue: 'openssl, libxml2',
    untrustedValue: ['openssl', untrustedValue],
    displayedUntrustedValue: `openssl, ${untrustedValue}`,
  },
];

beforeEach(() => {
  useFlaw().resetFlaw();
  tracking.setAegisMetadata({});
  runtime.value.flags = {};
});

afterEach(() => {
  for (const wrapper of wrappers.splice(0)) wrapper.unmount();
  tracking.setAegisMetadata({});
});

// Exercise real suggestion state and feedback tracking as well as metadata rendering.
describe.each(fields)('$field discarded suggestions', ({
  component,
  currentValue,
  displayedUntrustedValue,
  displayedValue,
  field,
  rejectedValue,
  untrustedValue,
}) => {
  function setup(modelValue = currentValue) {
    const wrapper = mountWithConfig(component, { props: { modelValue } });
    wrappers.push(wrapper);
    return wrapper;
  }

  it('shows a recorded proposal without applying it or offering it as a generated suggestion', async () => {
    const originalValue = structuredClone(currentValue);
    const wrapper = setup();
    const metadata = { [field]: [{ ...skip, value: rejectedValue }] };
    const recordedMetadata = structuredClone(metadata);
    tracking.setAegisMetadata(metadata);
    await nextTick();

    const generate = wrapper.get('[title="Generate AI suggestion"]');
    expect(generate.classes()).toContain('disabled');
    expect(generate.classes()).not.toContain('applied');
    await generate.trigger('click');
    await wrapper.get(warningSelector).trigger('click');

    const tooltip = wrapper.get('.aegis-tooltip');
    expect(tooltip.text()).toContain(`Discarded suggestion: ${displayedValue}`);
    expect(tooltip.text()).toContain(`Reason: ${skip.skip_description}`);
    expect(tooltip.text()).toContain('Confidence: 0.40');
    expect(tooltip.text()).toContain('Data quality: 0.80');
    expect(tooltip.text()).toContain('Tools used: cve_tool');
    expect(tooltip.text()).not.toContain('Generated by');
    expect(wrapper.find('.bi-info-circle, .dropdown-menu').exists()).toBe(false);
    expect(wrapper.find('.bi-arrow-counterclockwise, .bi-hand-thumbs-up, .bi-hand-thumbs-down').exists()).toBe(false);
    expect(wrapper.emitted('update:modelValue')).toBeUndefined();
    expect(wrapper.props('modelValue')).toEqual(originalValue);
    expect(tracking.getAegisMetadata()).toEqual(recordedMetadata);
  });

  it('keeps accepted feedback available when a later skipped proposal matches the current value', async () => {
    const accepted: AegisChangeEntry = {
      type: 'AI-Bot',
      timestamp: '2026-10-20T09:00:00Z',
      value: rejectedValue,
      explanation: 'Previously accepted suggestion',
    };
    tracking.setAegisMetadata({ [field]: [accepted] });
    const matchingValue = Array.isArray(rejectedValue) ? [...rejectedValue] : rejectedValue;
    const wrapper = setup(matchingValue);
    expect(wrapper.get('[title="Mark helpful"]').isVisible()).toBe(true);
    expect(wrapper.get('[title="Mark unhelpful"]').isVisible()).toBe(true);

    tracking.setAegisMetadata({ [field]: [accepted, { ...skip, value: rejectedValue }] });
    await nextTick();
    await wrapper.get(warningSelector).trigger('click');

    expect(wrapper.get('.aegis-tooltip').text()).toContain(`Discarded suggestion: ${displayedValue}`);
    expect(wrapper.get('.aegis-tooltip').text()).toContain(`Reason: ${skip.skip_description}`);
    expect(wrapper.get('.aegis-tooltip').text()).not.toMatch(/Generated by|Previously accepted suggestion/);
    expect(wrapper.find('.bi-info-circle, .bi-stars.applied').exists()).toBe(false);
    expect(wrapper.find('.bi-arrow-counterclockwise').exists()).toBe(false);
    expect(wrapper.get('[title="Mark helpful"]').attributes('aria-disabled')).toBe('false');
    expect(wrapper.get('[title="Mark unhelpful"]').attributes('aria-disabled')).toBe('false');
    expect(wrapper.emitted('update:modelValue')).toBeUndefined();
  });

  it('does not offer accepted feedback for a matching value recorded only in skipped attempts', async () => {
    tracking.setAegisMetadata({ [field]: [{ ...skip, value: rejectedValue }] });
    const matchingValue = Array.isArray(rejectedValue) ? [...rejectedValue] : rejectedValue;
    const wrapper = setup(matchingValue);
    await wrapper.get(warningSelector).trigger('click');

    expect(wrapper.get('.aegis-tooltip').text()).toContain(`Discarded suggestion: ${displayedValue}`);
    expect(wrapper.find('.bi-info-circle, .bi-stars.applied').exists()).toBe(false);
    expect(wrapper.find('.bi-hand-thumbs-up, .bi-hand-thumbs-down, .bi-arrow-counterclockwise').exists()).toBe(false);
    expect(wrapper.emitted('update:modelValue')).toBeUndefined();
  });

  it('renders stored markup literally after formatting the rejected value', async () => {
    tracking.setAegisMetadata({ [field]: [{ ...skip, value: untrustedValue }] });
    const wrapper = setup();
    await wrapper.get(warningSelector).trigger('click');

    const tooltip = wrapper.get('.aegis-tooltip');
    expect(tooltip.text()).toContain(`Discarded suggestion: ${displayedUntrustedValue}`);
    expect(tooltip.find('img, b, script').exists()).toBe(false);
    expect(wrapper.emitted('update:modelValue')).toBeUndefined();
  });
});
