/**
 * aegis_meta fixtures for the mock-server flaw handlers.
 *
 * The generated handlers in handlers.js serve flaws with `aegis_meta: null`.
 * withAegisMetaFixture wires pending-Aegis-suggestion scenarios into the
 * GET/PUT /osidb/api/v2/flaws/:uuid responses: a flaw whose id contains one
 * of the markers below receives the matching scenario, any other id keeps
 * `aegis_meta: null`.
 *
 *   /flaws/aegis-pending       trailing unprocessed AI-Bot-Pending entry whose
 *                              value differs from the current impact — the
 *                              pending-suggestion indicator is visible
 *   /flaws/aegis-superseded    pending entry followed by an AI-Bot entry —
 *                              the indicator is hidden (accept already happened)
 *   /flaws/aegis-value-match   pending entry whose value equals the current
 *                              impact — the indicator is hidden (AC4)
 *   /flaws/aegis-malformed     pending entry without a value — the indicator
 *                              is visible and the Accept action is disabled
 *
 * NOTE: handlers.js is regenerated by `yarn generate-osidb-mock`; re-apply
 * the withAegisMetaFixture wiring in the v2 flaw handlers afterwards.
 */

const explanation =
  'The CVSS metrics, flaw content, and impact-driven rule evaluation suggest a LOW impact rating for this flaw.';

const pendingEntry = {
  type: 'AI-Bot-Pending',
  timestamp: '2026-11-24T10:00:00.000Z',
  value: 'LOW',
  explanation,
  confidence: 0.86,
  data_quality: 0.74,
  tools_used: ['cvss-calculator', 'impact-rules', 'flaw-history'],
};

const acceptedEntry = {
  ...pendingEntry,
  type: 'AI-Bot',
  timestamp: '2026-11-24T12:00:00.000Z',
};

const malformedEntry = {
  type: 'AI-Bot-Pending',
  timestamp: '2026-11-24T10:00:00.000Z',
  explanation: 'Suggestion entry is missing its value field.',
  confidence: null,
  data_quality: null,
  tools_used: null,
};

export const aegisMetaFixtures = [
  {
    marker: 'aegis-pending',
    impact: 'CRITICAL',
    aegis_meta: { impact: [pendingEntry] },
  },
  {
    marker: 'aegis-superseded',
    impact: 'LOW',
    aegis_meta: { impact: [pendingEntry, acceptedEntry] },
  },
  {
    marker: 'aegis-value-match',
    impact: 'LOW',
    aegis_meta: { impact: [pendingEntry] },
  },
  {
    marker: 'aegis-malformed',
    impact: 'CRITICAL',
    aegis_meta: { impact: [malformedEntry] },
  },
];

export function withAegisMetaFixture(flaw, id) {
  const fixture = aegisMetaFixtures.find(({ marker }) => String(id ?? '').includes(marker));
  if (!fixture) return flaw;
  return { ...flaw, impact: fixture.impact, aegis_meta: fixture.aegis_meta };
}
